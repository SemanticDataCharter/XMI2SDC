#!/usr/bin/env bash
# XMI2SDC — PoC Initialization Script
#
# Prerequisites:
#   - SDCStudioSov running at localhost:8000
#   - Docker Engine 24+ with Compose V2
#
# Usage:
#   ./scripts/init-xmi2sdc.sh

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$PROJECT_DIR"

STUDIO_URL="${SDCSTUDIO_BASE_URL:-http://localhost:8000}"
API_TOKEN="${SDCSTUDIO_API_KEY:-poc-eval-token-2026}"

echo "========================================="
echo "  XMI2SDC — PoC Setup"
echo "========================================="
echo ""

# --------------------------------------------------
# Step 0: Preflight checks
# --------------------------------------------------
echo "[1/5] Checking prerequisites..."

# Docker
if ! command -v docker &>/dev/null; then
    echo "ERROR: Docker is not installed. Install Docker Engine 24+ first."
    exit 1
fi

if ! docker compose version &>/dev/null; then
    echo "ERROR: Docker Compose V2 is required. Update Docker or install the compose plugin."
    exit 1
fi

# SDCStudioSov
echo "  Checking SDCStudioSov at $STUDIO_URL ..."
if ! curl -sf "$STUDIO_URL/accounts/login/" >/dev/null 2>&1; then
    echo "ERROR: SDCStudioSov is not reachable at $STUDIO_URL"
    echo "  Run ./scripts/init-poc.sh in the SDCStudioSov directory first."
    exit 1
fi
echo "  SDCStudioSov is running."

echo ""

# --------------------------------------------------
# Step 1: Generate configuration
# --------------------------------------------------
echo "[2/5] Generating xmi2sdc.yaml..."

if [ -f xmi2sdc.yaml ]; then
    echo "  xmi2sdc.yaml already exists — keeping existing configuration."
else
    cat > xmi2sdc.yaml <<YAML
# XMI2SDC — PoC Configuration
# Generated by init-xmi2sdc.sh on $(date -Iseconds)
# For all available options see xmi2sdc.example.yaml

sdcstudio:
  base_url: "$STUDIO_URL"
  api_key: "$API_TOKEN"

cache:
  root: ".xmi2sdc-cache"
  ttl_hours: 24

audit:
  path: ".xmi2sdc-cache/audit.jsonl"
  log_level: "standard"

output:
  directory: "./output"
YAML
    echo "  Created xmi2sdc.yaml with:"
    echo "    base_url: $STUDIO_URL"
    echo "    api_key:  $API_TOKEN"
fi

echo ""

# --------------------------------------------------
# Step 2: Create directories
# --------------------------------------------------
echo "[3/5] Creating data and output directories..."
mkdir -p data output
echo "  ./data/   — place XMI files here"
echo "  ./output/ — mapping plans and artifacts will appear here"

echo ""

# --------------------------------------------------
# Step 3: Build Docker image
# --------------------------------------------------
echo "[4/5] Building XMI2SDC Docker image..."
docker compose -f docker-compose.xmi2sdc.yml build xmi2sdc 2>&1 | tail -5
echo "  Image built successfully."

echo ""

# --------------------------------------------------
# Step 4: Validate configuration
# --------------------------------------------------
echo "[5/5] Validating configuration..."

RESULT=$(docker compose -f docker-compose.xmi2sdc.yml run --rm xmi2sdc validate-config 2>&1) || true
if echo "$RESULT" | grep -qi "error\|refused\|failed"; then
    echo "  WARNING: Config validation returned errors."
    echo "  $RESULT"
    echo ""
    echo "  Check xmi2sdc.yaml and ensure the api_key matches the token"
    echo "  in SDCStudioSov (Django Admin > Auth Token > Tokens)."
else
    echo "  Configuration is valid."
fi

echo ""
echo "========================================="
echo "  XMI2SDC — Ready"
echo "========================================="
echo ""
echo "  Studio:   $STUDIO_URL"
echo "  Config:   xmi2sdc.yaml"
echo "  Data:     ./data/"
echo "  Output:   ./output/"
echo ""
echo "  Verify:"
echo "    docker compose -f docker-compose.xmi2sdc.yml run --rm xmi2sdc info"
echo ""
echo "  Convert an XMI file:"
echo "    docker compose -f docker-compose.xmi2sdc.yml run --rm xmi2sdc convert /data/model.xmi"
echo ""
echo "  Start MCP servers:"
echo "    docker compose -f docker-compose.xmi2sdc.yml up -d xmi2sdc-parser xmi2sdc-mapper"
echo ""
echo "  See README_XMI2SDC_PoC.md for full documentation."
echo "========================================="
